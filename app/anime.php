            <h2>9. O Significado das Cores do Super Saiyajin Blue e do Instinto Superior</h2>
            <p>A escolha cromática das transformações seguiu uma lógica de design e restrições de roteiro:</p>
            <ul>
                <li><strong>O Conceito do Blue:</strong> Toriyama explicou que, após a forma vermelha (Super Saiyajin Deus), que transmitia uma sensação de aura sutil e focada, a forma seguinte precisava transmitir calma, controle e compostura sobre o Ki divino. A cor ciano/azul foi escolhida para representar essa estabilidade mental.</li>
                <li><strong>A Mudança do Branco:</strong> Toriyama pretendia originalmente fazer a forma evoluída do SSJ Blue com cabelo branco. No entanto, ele percebeu que o vilão da saga seguinte (Zamasu Fundido) já teria cabelos brancos. Para evitar poluição visual e repetição de cores na tela durante os combates, guardou a cor branca/prateada exclusivamente para a forma definitiva do Instinto Superior Completo.</li>
            </ul>
