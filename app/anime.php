            <img src="/mini_sistema/includes/assets/cabelo.png" alt="cabelo" width="250" height="auto">
            <p>A mudança na cor do cabelo do Trunks do Futuro gerou grande confusão entre os fãs, mas tem uma explicação histórica de design:</p>
