            <h2>10. A Crise de Produção do Episódio 5 e a Virada do Filme do Broly</h2>
            <p>A qualidade técnica de <em>Dragon Ball Super</em> variou drasticamente por razões de bastidores da indústria de animação:</p>
            <ul>
                <li><strong>O Desastre do Episódio 5:</strong> A luta entre Goku e Beerus no planeta do Sr. Kaioh viralizou negativamente devido a desenhos deformados. Isso aconteceu porque a Toei aprovou o anime com pouquíssimo tempo de pré-produção logo após o sucesso do filme <em>A Ressurreição de 'F'</em>. Os animadores tinham prazos de dias para entregar centenas de quadros sem tempo para revisão.</li>
                <li><strong>A Reestruturação Técnica:</strong> Após as críticas, a Toei reorganizou seus cronogramas. No Torneio do Poder, trouxeram veteranos como Naotoshi Shida e Yuya Takahashi para animar as lutas principais. A reformulação culminou no filme <em>Dragon Ball Super: Broly</em>, onde o diretor de arte Naohiro Shintani mudou todo o traço para um estilo retrô, mais leve e fluido, que permitia movimentos de câmera extremamente dinâmicos sem sobrecarregar os animadores.</li>
            </ul>
