            <img src="/mini_sistema/includes/assets/beus.png" alt="beus" width="250" height="auto">
            <p>A concepção inicial de Beerus era totalmente diferente do deus felino carismático que conhecemos:</p>
            <ul>
                <li><strong>O Protótipo Original:</strong> O roteirista do filme <em>A Batalha dos Deuses</em>, Yusuke Watanabe, havia criado Beerus como um réptil maligno e sombrio que infectava o coração das pessoas com maldade pura.</li>
                <li><strong>A Intervenção de Toriyama:</strong> Ao assumir o projeto, Toriyama descartou a ideia do réptil e desenhou o personagem baseado em sua própria gata da raça Cornish Rex, chamada Debo.</li>
                <li><strong>A Inspiração do "Demônio":</strong> Debo ficou gravemente doente e o veterinário afirmou que ela não sobreviveria. Para a surpresa de todos, o animal se recuperou sozinho. O veterinário brincou dizendo que a gata devia ser algum tipo de "demônio reencarnado". Toriyama achou a história engraçada e usou a aparência da gata para criar um Deus da Destruição imprevisível, que alterna entre o sono, a comilança e o poder assustador.</li>
            </ul>
